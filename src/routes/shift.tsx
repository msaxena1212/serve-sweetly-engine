import { createFileRoute, redirect, useRouter } from "@tanstack/react-router";
import { useState } from "react";
import { Card, CardHeader, CardTitle, CardContent, CardFooter } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { toast } from "sonner";
import { Wallet, LogOut, CheckCircle, Sparkles, Copy, FileText } from "lucide-react";
import { getShiftStatusFn, openShiftFn, closeShiftFn } from "@/lib/api";
import { useConfig } from "@/lib/config-store";

export const Route = createFileRoute("/shift")({
  beforeLoad: async ({ context }) => {
    if (!context.session) {
      throw redirect({ to: '/login' });
    }
  },
  loader: async () => {
    // branchId read on client, loader uses fallback
    return await getShiftStatusFn({ data: { branchId: 'br-1' } });
  },
  component: ShiftPage,
});

function ShiftPage() {
  const router = useRouter();
  const { isActive, shift } = Route.useLoaderData();
  const { config } = useConfig();
  const branchId = config.activeBranchId;
  const [loading, setLoading] = useState(false);

  // Form states
  const [openingCash, setOpeningCash] = useState("");
  const [closingCash, setClosingCash] = useState("");
  const [expectedCash, setExpectedCash] = useState("");
  const [showDenom, setShowDenom] = useState(false);
  const [denoms, setDenoms] = useState<Record<number, string>>({
    500: "",
    200: "",
    100: "",
    50: "",
    20: "",
    10: "",
    1: "",
  });

  const [briefing, setBriefing] = useState<string | null>(null);
  const [generatingBriefing, setGeneratingBriefing] = useState(false);

  const generateBriefing = () => {
    setGeneratingBriefing(true);
    try {
      const dateStr = new Date().toLocaleDateString('en-IN', { weekday: 'long', day: 'numeric', month: 'short', year: 'numeric' });
      const exp = Number(expectedCash || shift?.expectedCash || 0);
      const act = Number(closingCash || 0);
      const variance = act - exp;
      const text = `📊 EXECUTIVE SHIFT & DAILY BRIEFING\n` +
        `Date: ${dateStr}\n` +
        `Shift: #${shift?.id ?? 1} (${shift?.status ?? 'Open'})\n` +
        `─────────────────────────────\n` +
        `• Opening Float: ₹${Number(shift?.openingCash ?? openingCash ?? 0).toFixed(2)}\n` +
        `• System Expected Cash: ₹${exp.toFixed(2)}\n` +
        (act > 0 ? `• Counted Physical Cash: ₹${act.toFixed(2)}\n• Cash Variance: ${variance >= 0 ? `+₹${variance.toFixed(2)} (Balanced/Surplus)` : `-₹${Math.abs(variance).toFixed(2)} (Shortfall)`}\n` : '') +
        `• Status: Verified and recorded in audit ledger.\n` +
        `─────────────────────────────\n` +
        `Generated by AI Operations Assistant · Forno POS`;
      setBriefing(text);
      toast.success("Executive briefing generated.");
    } catch {
      toast.error("Failed to generate briefing");
    } finally {
      setGeneratingBriefing(false);
    }
  };

  const copyBriefing = () => {
    if (!briefing) return;
    navigator.clipboard.writeText(briefing);
    toast.success("Copied executive briefing to clipboard!");
  };

  const updateDenom = (denom: number, countStr: string) => {
    const next = { ...denoms, [denom]: countStr };
    setDenoms(next);
    let total = 0;
    for (const [d, count] of Object.entries(next)) {
      const c = parseInt(count || "0", 10);
      if (!isNaN(c) && c > 0) total += Number(d) * c;
    }
    setClosingCash(total.toString());
  };

  const handleOpenShift = async () => {
    if (!openingCash || isNaN(Number(openingCash))) {
      toast.error("Please enter a valid opening cash amount.");
      return;
    }
    setLoading(true);
    try {
      await openShiftFn({ data: { openingCash: parseFloat(openingCash), branchId } });
      toast.success("Shift opened successfully.");
      router.invalidate();
    } catch (e: any) {
      toast.error(e.message || "Failed to open shift.");
    } finally {
      setLoading(false);
    }
  };

  const handleCloseShift = async () => {
    if (!closingCash || isNaN(Number(closingCash))) {
      toast.error("Please enter the actual cash in drawer.");
      return;
    }
    
    // expectedCash = openingCash + Cash Payments - Cash Refunds.
    const actual = parseFloat(closingCash);
    const expected = expectedCash ? parseFloat(expectedCash) : parseFloat(shift?.openingCash || "0");
    const variance = actual - expected;

    setLoading(true);
    try {
      await closeShiftFn({ data: { closingCash: actual, expectedCash: expected, variance, branchId } });
      toast.success(`Shift closed. Variance: ₹${variance.toFixed(2)}`);
      router.invalidate();
    } catch (e: any) {
      toast.error(e.message || "Failed to close shift.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="flex h-screen items-center justify-center bg-muted/40 p-6">
      <Card className="w-full max-w-md shadow-lg border-2">
        <CardHeader className="text-center space-y-1">
          <div className="w-12 h-12 bg-primary/10 rounded-full flex items-center justify-center mx-auto mb-2">
            <Wallet className="h-6 w-6 text-primary" />
          </div>
          <CardTitle className="text-2xl font-bold">Shift Management</CardTitle>
          <p className="text-sm text-muted-foreground">
            {isActive ? "Manage and close your active shift." : "Start a new shift to begin billing."}
          </p>
        </CardHeader>
        <CardContent className="space-y-4">
          {!isActive ? (
            <div className="space-y-4">
              <div className="bg-destructive/10 text-destructive text-sm p-3 rounded-md text-center font-medium">
                No active shift. POS billing is locked.
              </div>
              <div className="space-y-2">
                <label className="text-sm font-medium">Opening Cash (₹)</label>
                <Input 
                  type="number" 
                  placeholder="e.g. 5000" 
                  value={openingCash}
                  onChange={(e) => setOpeningCash(e.target.value)}
                  className="text-lg"
                />
                <p className="text-xs text-muted-foreground">Enter the physical cash amount currently in the drawer.</p>
              </div>
              <Button className="w-full h-11 text-base font-semibold" onClick={handleOpenShift} disabled={loading}>
                Open Shift
              </Button>
            </div>
          ) : (
            <div className="space-y-4">
              <div className="bg-green-500/10 text-green-700 text-sm p-3 rounded-md text-center font-medium flex items-center justify-center gap-2">
                <CheckCircle className="h-4 w-4" /> Shift Active since {new Date(shift.openedAt).toLocaleTimeString()}
              </div>
              <div className="grid grid-cols-2 gap-4 p-4 border rounded-md bg-card">
                <div>
                  <p className="text-xs text-muted-foreground font-semibold uppercase">Opening Cash</p>
                  <p className="text-xl font-bold">₹{parseFloat(shift.openingCash).toFixed(2)}</p>
                </div>
                <div>
                  <p className="text-xs text-muted-foreground font-semibold uppercase">Expected Cash</p>
                  <Input 
                    type="number" 
                    placeholder="Auto-calculated" 
                    value={expectedCash}
                    onChange={(e) => setExpectedCash(e.target.value)}
                    className="h-8 text-sm mt-1"
                  />
                </div>
              </div>

              <div className="space-y-2 pt-2">
                <div className="flex items-center justify-between">
                  <label className="text-sm font-medium text-destructive">Actual Cash in Drawer (₹) *</label>
                  <button
                    type="button"
                    onClick={() => setShowDenom(!showDenom)}
                    className="text-xs text-primary hover:underline font-medium"
                  >
                    {showDenom ? "Hide Counter" : "+ Denominations Count"}
                  </button>
                </div>

                {showDenom && (
                  <div className="p-3 bg-muted/40 rounded-lg space-y-2 text-xs border">
                    <p className="font-semibold text-muted-foreground">Currency Note Counter</p>
                    <div className="grid grid-cols-2 gap-2">
                      {[500, 200, 100, 50, 20, 10].map((d) => (
                        <div key={d} className="flex items-center gap-1.5">
                          <span className="w-12 font-mono text-muted-foreground">₹{d} ×</span>
                          <Input
                            type="number"
                            min="0"
                            placeholder="0"
                            value={denoms[d]}
                            onChange={(e) => updateDenom(d, e.target.value)}
                            className="h-7 text-xs text-right"
                          />
                        </div>
                      ))}
                      <div className="flex items-center gap-1.5 col-span-2">
                        <span className="w-20 font-mono text-muted-foreground">Coins total:</span>
                        <Input
                          type="number"
                          min="0"
                          placeholder="0"
                          value={denoms[1]}
                          onChange={(e) => updateDenom(1, e.target.value)}
                          className="h-7 text-xs text-right"
                        />
                      </div>
                    </div>
                  </div>
                )}

                <Input 
                  type="number" 
                  placeholder="Count physical cash" 
                  value={closingCash}
                  onChange={(e) => setClosingCash(e.target.value)}
                  className="text-lg border-destructive/50 focus-visible:ring-destructive"
                />
              </div>
              
              <Button variant="destructive" className="w-full h-11 text-base font-semibold" onClick={handleCloseShift} disabled={loading}>
                <LogOut className="h-4 w-4 mr-2" />
                Close Shift
              </Button>

              <div className="pt-2 border-t space-y-2">
                <Button variant="outline" size="sm" className="w-full gap-1.5 text-xs" onClick={generateBriefing} disabled={generatingBriefing}>
                  <Sparkles className="h-3.5 w-3.5 text-primary" />
                  Generate AI Shift Briefing
                </Button>
                {briefing && (
                  <div className="p-3 bg-muted/50 rounded-md border text-xs space-y-2">
                    <pre className="whitespace-pre-wrap font-mono text-[11px] leading-relaxed">{briefing}</pre>
                    <Button variant="secondary" size="sm" className="w-full h-7 text-xs gap-1.5" onClick={copyBriefing}>
                      <Copy className="h-3 w-3" /> Copy for WhatsApp / Telegram
                    </Button>
                  </div>
                )}
              </div>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
